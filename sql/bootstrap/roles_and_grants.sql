-- Schemas and roles for a live Snowflake account (A10). DuckDB bootstrap does not run this file.
-- CHURN_APPROVER may update APPROVALS and nothing else. CHURN_SENDER may read the sender view only.
CREATE SCHEMA IF NOT EXISTS THESIS_SYNTH;
CREATE SCHEMA IF NOT EXISTS CHURN_OPS;
CREATE SCHEMA IF NOT EXISTS CHURN_PRIVATE;

CREATE ROLE IF NOT EXISTS CHURN_APP;
CREATE ROLE IF NOT EXISTS CHURN_ANALYST;
CREATE ROLE IF NOT EXISTS CHURN_APPROVER;
CREATE ROLE IF NOT EXISTS CHURN_SENDER;

GRANT USAGE ON SCHEMA THESIS_SYNTH TO ROLE CHURN_APP;
GRANT USAGE ON SCHEMA CHURN_OPS TO ROLE CHURN_APP;
GRANT USAGE ON SCHEMA CHURN_PRIVATE TO ROLE CHURN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA CHURN_OPS TO ROLE CHURN_APP;

GRANT USAGE ON SCHEMA CHURN_OPS TO ROLE CHURN_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA CHURN_OPS TO ROLE CHURN_ANALYST;
GRANT SELECT ON ALL VIEWS IN SCHEMA CHURN_OPS TO ROLE CHURN_ANALYST;

GRANT USAGE ON SCHEMA CHURN_OPS TO ROLE CHURN_APPROVER;
GRANT SELECT, UPDATE ON TABLE CHURN_OPS.APPROVALS TO ROLE CHURN_APPROVER;

GRANT USAGE ON SCHEMA CHURN_OPS TO ROLE CHURN_SENDER;
GRANT SELECT ON VIEW CHURN_OPS.OUTBOX_FOR_SENDER TO ROLE CHURN_SENDER;
